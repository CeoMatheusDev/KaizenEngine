#!/usr/bin/env python3
"""Extract the CPU-side occlusion functions from the engine sources into one
generated header, so tests/kaizen can compile and test them without an engine
build.

Why extraction instead of inclusion: the shipping translation units pull in
platform_config.h and the *.gen.h headers that only exist after a SCons build,
and tests/kaizen is defined by not needing one (see ../README.md). The function
*bodies* are the part under test, so they are taken verbatim from the engine
source at build time and compiled against the small type shims in the test.
The shims mirror the members the bodies touch; the bodies themselves are not
edited by anything except the line that opens the function.

Each entry below is (source file, regex matching the definition line, emitted
name, emitted signature, prologue). If a definition is not found exactly once
the script fails: a silently skipped function would mean the shipped patch lost
its coverage without anyone noticing, which is the failure mode worth being loud
about. If a refactor legitimately changes a signature, update the regex here -
the test then still checks the body against the reference implementations.
"""

import argparse
import os
import re
import sys

FUNCTIONS = [
    (
        "servers/rendering/renderer_scene_occlusion_cull.cpp",
        r"^void RendererSceneOcclusionCull::HZBuffer::clear\(\) \{",
        "hzbuffer_clear",
        "void hzbuffer_clear()",
        "",
    ),
    (
        "servers/rendering/renderer_scene_occlusion_cull.cpp",
        r"^void RendererSceneOcclusionCull::HZBuffer::resize\(const Size2i &p_size\) \{",
        "hzbuffer_resize",
        "void hzbuffer_resize(const Size2i &p_size)",
        "",
    ),
    (
        "servers/rendering/renderer_scene_occlusion_cull.cpp",
        r"^void RendererSceneOcclusionCull::HZBuffer::update_mips\(\) \{",
        "hzbuffer_update_mips",
        "void hzbuffer_update_mips()",
        "",
    ),
    (
        "modules/raycast/raycast_occlusion_cull.cpp",
        r"^void RaycastOcclusionCull::RaycastHZBuffer::sort_rays\(const Vector3 &p_camera_dir, bool p_orthogonal\) \{",
        "raycast_sort_rays",
        "void raycast_sort_rays(const Vector3 &p_camera_dir, bool p_orthogonal)",
        "\t// sort_rays ignores both parameters: it transposes, it does not sort.\n"
        "\t(void)p_camera_dir;\n\t(void)p_orthogonal;\n",
    ),
    (
        "modules/raycast/raycast_occlusion_cull.cpp",
        r"^void RaycastOcclusionCull::RaycastHZBuffer::_generate_camera_rays\(const CameraRayThreadData \*p_data, int p_from, int p_to\) \{",
        "raycast_generate_camera_rays",
        "void raycast_generate_camera_rays(const CameraRayThreadData *p_data, int p_from, int p_to)",
        "",
    ),
]


def find_body(text, definition_regex, source):
    """Return the text between the function's opening brace and its matching close."""
    matches = [m for m in re.finditer(definition_regex, text, re.MULTILINE)]
    if len(matches) != 1:
        raise SystemExit(
            "%s: expected exactly one definition matching %r, found %d. "
            "The engine function moved or changed signature; update FUNCTIONS in "
            "this script, and make sure the change is reflected in the matching "
            "patches/*/0*.md note." % (source, definition_regex, len(matches))
        )
    start = matches[0].end() - 1  # on the '{'
    depth = 0
    in_line_comment = False
    in_block_comment = False
    index = start
    length = len(text)
    while index < length:
        char = text[index]
        nxt = text[index + 1] if index + 1 < length else ""
        if in_line_comment:
            if char == "\n":
                in_line_comment = False
        elif in_block_comment:
            if char == "*" and nxt == "/":
                in_block_comment = False
                index += 1
        elif char == "/" and nxt == "/":
            in_line_comment = True
        elif char == "/" and nxt == "*":
            in_block_comment = True
            index += 1
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : index], text.count("\n", 0, matches[0].start()) + 1
        index += 1
    raise SystemExit("%s: definition matching %r is not brace-balanced" % (source, definition_regex))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo-root", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    cache = {}
    parts = [
        "// GENERATED by extract_source_bodies.py - do not edit.\n"
        "// Bodies copied verbatim from the engine sources listed above each function.\n"
    ]
    current = None
    for source, regex, name, signature, prologue in FUNCTIONS:
        if source not in cache:
            path = os.path.join(args.repo_root, source)
            if not os.path.isfile(path):
                raise SystemExit("missing source file: %s" % path)
            with io_open(path) as handle:
                cache[source] = handle.read()
        body, line = find_body(cache[source], regex, source)
        parts.append(
            "\n// ---- %s:%d  %s\nstatic %s {\n%s%s}\n"
            % (source, line, name, signature, prologue, body)
        )
        if current is None:
            current = (source, line)

    with io_open(args.out, "w") as handle:
        handle.write("".join(parts))
    print("extracted %d function bodies -> %s" % (len(FUNCTIONS), args.out))
    return 0


def io_open(path, mode="r"):
    return open(path, mode, encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
